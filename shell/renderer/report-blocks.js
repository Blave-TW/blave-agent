  // 只上 keyword / string / number / comment 四類,其餘中性(canon Code syntax)
  function pyTokens(src) {
    var out = [];
    var i = 0;
    var plain = "";
    function flush() {
      if (plain) {
        out.push({ k: null, v: plain });
        plain = "";
      }
    }
    while (i < src.length) {
      var c = src.charAt(i);
      if (c === "#") {
        var end = src.indexOf("\n", i);
        if (end < 0) end = src.length;
        flush();
        out.push({ k: "c", v: src.slice(i, end) });
        i = end;
      } else if (c === '"' || c === "'") {
        var quote = src.substr(i, 3) === c + c + c ? c + c + c : c;
        var j = i + quote.length;
        while (j < src.length) {
          if (src.charAt(j) === "\\") {
            j += 2;
            continue;
          }
          if (src.substr(j, quote.length) === quote) {
            j += quote.length;
            break;
          }
          j++;
        }
        flush();
        out.push({ k: "s", v: src.slice(i, Math.min(j, src.length)) });
        i = j;
      } else if (/[0-9]/.test(c) && !/[A-Za-z_0-9]/.test(src.charAt(i - 1) || "")) {
        var k = i;
        while (k < src.length && /[0-9._eExXa-fA-F]/.test(src.charAt(k))) k++;
        flush();
        out.push({ k: "n", v: src.slice(i, k) });
        i = k;
      } else if (/[A-Za-z_]/.test(c)) {
        var w = i;
        while (w < src.length && /[A-Za-z_0-9]/.test(src.charAt(w))) w++;
        var word = src.slice(i, w);
        if (PY_KEYWORDS[word] === 1) {
          flush();
          out.push({ k: "k", v: word });
        } else {
          plain += word;
        }
        i = w;
      } else {
        plain += c;
        i++;
      }
    }
    flush();
    return out;
  }

