  BLOCKS.table = function (b) {
    var cols = arr(b.columns);
    var rows = arr(b.rows);
    if (!cols.length) return null;
    var wrap = el("div", "rb-table-wrap");
    var table = el("table", "rb-table");
    var thead = el("thead");
    var htr = el("tr");
    cols.forEach(function (c) {
      htr.appendChild(monoLabel(el("th", alignClass(c.align)), str(c.label)));
    });
    thead.appendChild(htr);
    table.appendChild(thead);
    var tbody = el("tbody");
    rows.forEach(function (r) {
      var tr = el("tr");
      cols.forEach(function (c) {
        var cell = r ? r[c.key] : null;
        var text = cell == null ? "" : typeof cell === "number" ? String(cell) : cell;
        // format 是漲跌語意色的閘門:只有 number / percent 的欄套用,text / date
        // 一律不上色(契約 §3 table)
        var toned = c.format === "number" || c.format === "percent";
        var td = el("td", (alignClass(c.align) + (toned ? signTone(text) : "")).trim());
        if (text === "") td.textContent = DASH;
        else monoShapes(td, text);
        tr.appendChild(td);
      });
      tbody.appendChild(tr);
    });
    table.appendChild(tbody);
    wrap.appendChild(table);
    return wrap;
  };

