  BLOCKS.scatter = function (b) {
    var pts = arr(b.points);
    if (!pts.length) return null;
    var W = 680, H = 240, right = 672, bottom = 190, xLabelY = 210;
    var yUnit = str(b.y_unit);
    var xUnit = str(b.x_unit);
    var top = plotTop(15, yUnit);
    var xs = pts.map(function (p) {
      return p.x;
    });
    var ys = pts.map(function (p) {
      return p.y;
    });
    var xScale = niceScale(Math.min.apply(null, xs), Math.max.apply(null, xs));
    var yScale = niceScale(Math.min.apply(null, ys), Math.max.apply(null, ys));
    var padL = yGutter(yScale, yUnit);
    var x0 = padL, x1 = 660 - xUnitPad(xUnit);
    var s = chartSvg(b, W, H, false);
    watermark(s, 668, bottom - 7);
    var yAt = yAxis(s, yScale, top, bottom, padL, right, yUnit);
    var xAt = function (v) {
      return x0 + ((v - xScale.lo) / (xScale.hi - xScale.lo || 1)) * (x1 - x0);
    };

    // 回歸線是衍生註記、不是第二序列 → 註記線家族預設樣式
    var reg = b.regression;
    if (reg) {
      var a = reg.slope, c = reg.intercept;
      // 裁到繪圖區內:回歸線延伸到 y 範圍外會畫進軸標區
      var ends = [xScale.lo, xScale.hi].map(function (x) {
        var y = a * x + c;
        if (a !== 0 && y < yScale.lo) return [(yScale.lo - c) / a, yScale.lo];
        if (a !== 0 && y > yScale.hi) return [(yScale.hi - c) / a, yScale.hi];
        return [x, Math.min(yScale.hi, Math.max(yScale.lo, y))];
      });
      if (ends[1][0] > ends[0][0]) {
        s.appendChild(
          svgEl("line", {
            class: "rb-ref",
            x1: xAt(ends[0][0]),
            y1: yAt(ends[0][1]),
            x2: xAt(ends[1][0]),
            y2: yAt(ends[1][1]),
          })
        );
      }
    }

    // 全部省略 role = 單一母體,全點 data-1
    var twoClass = pts.some(function (p) {
      return p.role === "focus" || p.role === "context";
    });
    pts.forEach(function (p) {
      var focus = twoClass && p.role === "focus";
      var px = xAt(p.x), py = yAt(p.y);
      s.appendChild(
        svgEl("circle", {
          class: focus || !twoClass ? "rb-pt1" : "rb-pt2",
          cx: px,
          cy: py,
          r: focus ? 6 : 5,
        })
      );
      if (!p.label) return;
      // 標籤直接放點旁(五個點的圖用 legend 是繞路)。焦點點一律往左放(mockup
      // 做法,把右側留給 context 點的標籤);其餘看落在左右哪半邊
      var left = focus || px > x0 + (x1 - x0) * 0.6;
      var ly = py < top + 14 ? py + 14 : py - 6; // 貼上緣的點,標籤改放下方
      s.appendChild(
        svgText(px + (left ? -12 : 12), ly, str(p.label), {
          class: "rb-pt-label" + (focus ? " is-focus" : ""),
          "text-anchor": left ? "end" : "start",
        })
      );
    });

    [0, 1, 2].forEach(function (k) {
      var v = xScale.lo + ((xScale.hi - xScale.lo) * k) / 2;
      s.appendChild(
        svgText(xAt(v), xLabelY, fmtAxis(v, xUnit, xScale.lo <= 0, xScale.dp), {
          "text-anchor": k === 0 ? "start" : k === 2 ? "end" : "middle",
        })
      );
    });
    xUnitLabel(s, xUnit, right, xLabelY);

    var wrap = el("div");
    wrap.appendChild(s);
    return wrap;
  };

