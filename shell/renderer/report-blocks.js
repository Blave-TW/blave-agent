  // 圖內文字寬(viewBox 單位,字級 10px)。數字片段落在 tspan.mono(Roboto Mono
  // 字距 0.6em),漢字與全形標點(（）：／ 在 FF00–FFEF)1em;拉丁 sans 也按 0.6em 算,
  // 多數字母略寬於實際,但 W / M 這類大寫約 0.9em 會少估。
  // 不用 canvas 量:SVG 佈局只算一次,字型還沒載入時量到的是退場字型
  var FULL_WIDTH = /[\u2e80-\u9fff\uf900-\ufaff\uff00-\uffef]/;
  function textWidth(text) {
    var w = 0;
    for (var i = 0; i < text.length; i++) {
      w += FULL_WIDTH.test(text.charAt(i)) ? 10 : 6;
    }
    return w;
  }

  // 縱軸標籤區寬 = 繪圖區左界。最寬的刻度標(含詞單位那一行)決定它:五位數帶
  // 千分位是 36px,固定 36 的舊 gutter 只剩 30px 給標籤,45,000 會被 viewBox
  // 切成 5,000。標籤到格線 6px、到 viewBox 左緣 2px;窄標籤維持原本 36 不動
  function yGutter(scale, unit, signed) {
    if (signed == null) signed = scale.lo <= 0;
    var w = isWordUnit(unit) ? textWidth(unit) : 0;
    scale.ticks.forEach(function (t) {
      w = Math.max(w, textWidth(fmtAxis(t, unit, signed, scale.dp)));
    });
    return Math.max(36, 2 + w + 6);
  }

  // 左側 y 軸:格線 + 右對齊的軸標。單位一律由呼叫端給——契約的 y_unit / x_unit
  // 是純顯示後綴,沒帶就印裸數字;web 絕不自己猜一條序列是 % 還是 USDT。
  // 詞單位不逐刻度重複(fmtAxis 已擋),改標在頂刻度上方那一行、與刻度共用右界。
  // crisp = 1:1 像素繪製的圖(candlestick):1px 格線落在半像素才不糊成兩條淡線
  function yAxis(s, scale, top, bottom, padL, right, unit, signed, crisp) {
    if (signed == null) signed = scale.lo <= 0;
    var yAt = function (v) {
      return bottom - ((v - scale.lo) / (scale.hi - scale.lo)) * (bottom - top);
    };
    scale.ticks.forEach(function (t) {
      var y = crisp ? Math.round(yAt(t)) + 0.5 : yAt(t);
      gridLine(s, padL, y, right);
      s.appendChild(
        svgText(padL - 6, y + 3, fmtAxis(t, unit, signed, scale.dp), {
          "text-anchor": "end",
        })
      );
    });
    if (isWordUnit(unit)) {
      s.appendChild(svgText(padL - 6, top - 11, unit, { "text-anchor": "end" }));
    }
    return yAt;
  }

